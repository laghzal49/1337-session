-- ── Helpers ────────────────────────────────────────────────────────────
--- Convert an onedark-style {fg, bg, fmt, sp} table into native nvim_set_hl attrs.
local function resolve(spec)
  if not spec or type(spec) ~= 'table' then return spec end
  local out = {}
  -- Resolve $variable references against the palette
  for _, key in ipairs({ 'fg', 'bg', 'sp' }) do
    local v = spec[key]
    if type(v) == 'string' and v:sub(1, 1) == '$' then
      out[key] = p[v:sub(2)]
    elseif v and v ~= 'NONE' then
      out[key] = v
    end
  end
  -- Convert fmt string to boolean attributes
  local fmt = spec.fmt
  if fmt then
    for token in fmt:gmatch('[^,]+') do
      local t = token:match('^%s*(.-)%s*$')
      if     t == 'bold'          then out.bold = true
      elseif t == 'italic'        then out.italic = true
      elseif t == 'underline'     then out.underline = true
      elseif t == 'undercurl'     then out.undercurl = true
      elseif t == 'strikethrough' then out.strikethrough = true
      end
    end
  end
  -- Pass through any native keys already present
  for _, key in ipairs({ 'bold', 'italic', 'underline', 'undercurl', 'strikethrough', 'link', 'default' }) do
    if spec[key] ~= nil and out[key] == nil then out[key] = spec[key] end
  end
  return out
end

local function hi(name, spec) vim.api.nvim_set_hl(0, name, resolve(spec)) end
local function groups(names, spec)
  for name in names:gmatch('%S+') do hi(name, spec) end
end

