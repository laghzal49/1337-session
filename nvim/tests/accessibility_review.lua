-- Full config: nvim --headless '+lua dofile("nvim/tests/accessibility_review.lua")' +qa!
local access, ui, surfaces = require('config.accessibility'), require('config.ui'), require('config.surfaces')
access.setup()
access.set(false)
require('lazy').load({plugins={'lualine.nvim','bufferline.nvim'}})
local icons = require('mini.icons')
local old_font, old_border, old_edge = vim.g.have_nerd_font, ui.border, surfaces.edge
local buf = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(buf,0,-1,false,{'unchanged data'})
local tick, windows, theme = vim.api.nvim_buf_get_changedtick(buf), #vim.api.nvim_list_wins(), vim.g.colors_name
vim.diagnostic.enable(false,{bufnr=buf})
vim.cmd('UIAccessibility on')
assert(ui.accessible and vim.g.have_nerd_font == false and ui.border == 'single','preset did not apply')
assert(icons.config.style == 'ascii','loaded icon provider not updated')
assert(ui.icon('modified') == '*' and ui.icon('dot') == '.','plain icon fallback missing')
assert(surfaces.edge == '#A9B9D6','strong border token missing')
local border = vim.api.nvim_get_hl(0,{name='SnacksPickerBorder',link=false})
assert(border.fg == tonumber('A9B9D6',16),'picker border remains low contrast')
assert(not vim.api.nvim_get_hl(0,{name='Comment',link=false}).italic,'decorative comment italics remain')
assert(not vim.diagnostic.is_enabled({bufnr=buf}),'preset reset diagnostic disable toggle')
assert(vim.api.nvim_buf_get_changedtick(buf) == tick and #vim.api.nvim_list_wins() == windows,'preset changed data or windows')
assert(vim.g.colors_name == theme,'preset changed active theme')
assert(vim.fn.maparg('<leader>ua','n') ~= '', 'preset toggle key missing')
vim.cmd('UIAccessibility toggle')
assert(not ui.accessible and ui.border == old_border and surfaces.edge == old_edge,'original tokens not restored')
assert(vim.g.have_nerd_font == old_font and icons.config.style == (old_font == false and 'ascii' or 'glyph'),'font preferences not restored')
assert(vim.api.nvim_get_hl(0,{name='Comment',link=false}).italic,'theme attributes not restored')
-- User highlight overrides survive both transitions without reloading the theme.
local original_comment = vim.api.nvim_get_hl(0,{name='Comment',link=true})
vim.api.nvim_set_hl(0,'Comment',{fg='#ABCDEF',italic=true,bold=true})
vim.api.nvim_set_hl(0,'UserAccessibilityMarker',{fg='#123456'})
access.set(true)
assert(vim.api.nvim_get_hl(0,{name='Comment',link=false}).fg == tonumber('ABCDEF',16),'enable reset custom comment color')
access.set(false)
local custom = vim.api.nvim_get_hl(0,{name='Comment',link=false})
assert(custom.fg == tonumber('ABCDEF',16) and custom.italic and custom.bold,'disable lost custom comment override')
assert(vim.api.nvim_get_hl(0,{name='UserAccessibilityMarker',link=false}).fg == tonumber('123456',16),'unrelated highlight override was reset')
-- An explicit override made during accessibility remains the latest preference.
access.set(true)
vim.api.nvim_set_hl(0,'Comment',{fg='#FEDCBA',italic=false})
access.set(false)
assert(vim.api.nvim_get_hl(0,{name='Comment',link=false}).fg == tonumber('FEDCBA',16),'disable discarded a newer user override')
vim.api.nvim_set_hl(0,'Comment',original_comment)
-- A user who already selected plain icons retains that preference after reset.
vim.g.have_nerd_font = false
access.set(true); access.set(false)
assert(vim.g.have_nerd_font == false,'reset overwrote pre-existing ASCII preference')
vim.g.have_nerd_font = old_font
-- Contrast persists on theme changes and reset retains the user's theme.
vim.cmd.colorscheme('habamax')
access.set(true)
assert(vim.g.colors_name == 'habamax' and vim.api.nvim_get_hl(0,{name='SnacksPickerBorder',link=false}).fg == tonumber('A9B9D6',16),'custom theme lost contrast or was replaced')
access.set(false)
assert(vim.g.colors_name == 'habamax','reset replaced user colorscheme')
-- Switching themes while enabled invalidates snapshots from the old theme.
access.set(true)
vim.cmd.colorscheme(theme)
access.set(false)
assert(vim.api.nvim_get_hl(0,{name='SnacksPickerBorder',link=false}).fg == tonumber(old_edge:sub(2),16),'theme change retained accessible border after reset')
vim.diagnostic.enable(true,{bufnr=buf})
access.set(false)
print('ACCESSIBILITY PASS: live toggle/reset, loaded plugin refresh, contrast/plain glyphs, data/windows/theme/diagnostic safety')
