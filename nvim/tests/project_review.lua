local project = require('config.project')
local cwd = vim.fn.getcwd()
-- Keep the fixture below the editor cwd so a host-wide /tmp/.git marker
-- cannot change the expected fallback root.
local root = cwd .. '/.project-review-' .. vim.fn.getpid() .. '-' .. string.format('%.0f', vim.uv.hrtime())
local function run()
  vim.fn.mkdir(root .. '/node/src', 'p')
  vim.fn.mkdir(root .. '/python/tests', 'p')
  vim.fn.mkdir(root .. '/local/.git', 'p')
  vim.fn.writefile({ '{"scripts":{"test":"echo ok"}}' }, root .. '/node/package.json')
  vim.cmd.edit(vim.fn.fnameescape(root .. '/node/src/main.js'))
  assert(project.root() == root .. '/node', 'nested Node files must find package tasks')
  vim.cmd.edit(vim.fn.fnameescape(root .. '/python/tests/test_new.py'))
  assert(project.root() == cwd, 'unmarked projects use editor cwd')
  vim.fn.writefile({ '[pytest]' }, root .. '/python/pytest.ini')
  vim.api.nvim_exec_autocmds('BufWritePost', { pattern = root .. '/python/pytest.ini' })
  assert(project.root() == root .. '/python', 'new project markers must invalidate root cache')
  vim.cmd.enew({ bang = true })
  vim.cmd.lcd(vim.fn.fnameescape(root .. '/local'))
  assert(project.root() == root .. '/local', 'unnamed buffers respect window-local cwd: ' .. project.root())
end
local ok, err = xpcall(run, debug.traceback)
vim.cmd.cd(vim.fn.fnameescape(cwd))
vim.fn.delete(root, 'rf')
assert(ok, err)
print('PROJECT REVIEW PASS: Node/Python discovery, marker invalidation, local cwd')
